const param = (name, type, description, required = true) => ({ name, type, description, required })
const answers = (...items) => items.map(([value, meaning]) => ({ value, meaning }))

const payloadFields = () => [
  param('payload', 'table', 'A Lua table containing the notification contents and display options. Include at least one of payload.title or payload.message.'),
  param('payload.title', 'string', 'Optional heading shown above the message. Add either a title or a message.', false),
  param('payload.message', 'string', 'Optional notification text. Supports safe Markdown. Add either a title or a message.', false),
  param('payload.duration', 'integer', 'How long the notification stays visible, in milliseconds. Defaults to 5000; maximum 120000.', false),
  param('payload.type', '"info" | "success" | "warning" | "error"', 'Visual style and icon. Defaults to info. The aliases inform and warn are also accepted.', false),
  param('payload.position', '"top-left" | "top-center" | "top-right" | "bottom-left" | "bottom-center" | "bottom-right" | "center-left" | "center-right" | "top" | "bottom"', 'Screen location. Defaults to top-right.', false),
  param('payload.icon', 'string', 'Optional icon name or safe image URL to replace the default icon.', false),
  param('payload.iconColor', 'string', 'Optional CSS color for the icon.', false),
  param('payload.iconAnimation', '"spin" | "spinPulse" | "spinReverse" | "pulse" | "beat" | "fade" | "beatFade" | "bounce" | "shake"', 'Optional icon animation.', false),
  param('payload.alignIcon', '"top" | "center"', 'Vertical icon alignment. Defaults to center.', false),
  param('payload.id', 'string or number', 'Optional ID. A new notification with the same ID replaces the existing one.', false),
  param('payload.showDuration', 'boolean', 'Set false to hide the notification lifetime indicator.', false),
  param('payload.style', 'table', 'Optional appearance overrides using CSS style values. Nested title, description, message, and text selectors can each have their own style values.', false),
  param('payload.style.<CSS property>', 'scalar', 'A supported CSS value for the notification, for example backgroundColor or borderColor. Nested objects are ignored here.', false),
  param('payload.style.title / description / message / text', 'table', 'Optional styles for that part of the notification. Use simple CSS property and value pairs inside each selector.', false),
]

